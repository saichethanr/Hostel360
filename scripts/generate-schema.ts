import { openDatabase } from "../server/db.ts";
const db = openDatabase(":memory:");
const tables = db
  .prepare(
    "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid",
  )
  .all();
console.log(`-- Initial Hostel360 schema. Application tables are private, never exposed via PostgREST.
BEGIN;
CREATE SCHEMA IF NOT EXISTS hostel360;
SET LOCAL search_path TO hostel360;
CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());`);
for (const table of tables)
  console.log(
    String(table.sql)
      .replace(/CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ")
      .replace(
        /\bid INTEGER PRIMARY KEY/gi,
        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
      )
      .replace(/expires INTEGER/, "expires BIGINT") + ";",
  );
for (const row of db
  .prepare(
    "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL",
  )
  .all())
  console.log(
    String(row.sql).replace(
      /CREATE (UNIQUE )?INDEX /,
      "CREATE $1INDEX IF NOT EXISTS ",
    ) + ";",
  );
console.log(`CREATE UNIQUE INDEX IF NOT EXISTS users_auth_identity ON users(auth_id) WHERE auth_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS student_roll_casefold ON students(lower(roll));
INSERT INTO settings (key,value) VALUES ('hostel_name','Hostel360'),('daily_rate','11000'),('demo','false') ON CONFLICT DO NOTHING;
INSERT INTO schema_migrations (version) VALUES ('20261111000000') ON CONFLICT DO NOTHING;
REVOKE ALL ON SCHEMA hostel360 FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA hostel360 FROM PUBLIC;
COMMIT;`);
db.close();
