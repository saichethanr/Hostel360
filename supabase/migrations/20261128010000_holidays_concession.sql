-- Apply as the schema owner after the meal tokens migration.
-- Holidays: days the Admin declares the mess closed; no attendance is needed
-- and mess finalization neither expects nor charges them.
-- Leave concession: whether approved leave days are free of mess charges.
-- Medical leave no longer requires a document.
BEGIN;
SET LOCAL search_path TO hostel360;
CREATE TABLE holidays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  date TEXT NOT NULL,
  name TEXT NOT NULL,
  created_by INTEGER,
  created_at TEXT NOT NULL,
  UNIQUE(community_id,date)
);
ALTER TABLE holidays ENABLE ROW LEVEL SECURITY;
ALTER TABLE holidays FORCE ROW LEVEL SECURITY;
CREATE POLICY community_isolation ON holidays
  USING (community_id=nullif(current_setting('app.community_id',true),'')::integer)
  WITH CHECK (community_id=nullif(current_setting('app.community_id',true),'')::integer);
REVOKE ALL ON holidays FROM PUBLIC;

-- Existing approved leave was always free of mess charges.
ALTER TABLE leaves ADD COLUMN concession INTEGER NOT NULL DEFAULT 1 CHECK (concession IN (0,1));
ALTER TABLE leaves ADD COLUMN requested_by INTEGER;
DO $$
DECLARE c TEXT;
BEGIN
  SELECT conname INTO c FROM pg_constraint
    WHERE conrelid='hostel360.leaves'::regclass AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%Medical%document_id%';
  IF c IS NOT NULL THEN
    EXECUTE format('ALTER TABLE leaves DROP CONSTRAINT %I', c);
  END IF;
END $$;

DO $$
DECLARE r TEXT;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON holidays FROM %I',r);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hostel360_app') THEN
    GRANT SELECT,INSERT,UPDATE,DELETE ON holidays TO hostel360_app;
    GRANT USAGE,SELECT ON SEQUENCE holidays_id_seq TO hostel360_app;
  END IF;
END $$;
INSERT INTO schema_migrations(version) VALUES ('20261128010000');
COMMIT;
