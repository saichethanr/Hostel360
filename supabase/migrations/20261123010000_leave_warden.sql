-- Apply as the schema owner after the communities migration. Adds the Warden
-- role and student leave requests (casual or medical, approved by a Warden).
BEGIN;
SET LOCAL search_path TO hostel360;
ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('Admin','Manager','Student','Warden'));
CREATE TABLE leaves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  student_id INTEGER NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('Casual','Medical')),
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL CHECK (end_date >= start_date),
  reason TEXT NOT NULL,
  document_id INTEGER REFERENCES documents(id),
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected','Cancelled')),
  decided_by INTEGER,
  decision_reason TEXT NOT NULL DEFAULT '',
  decided_at TEXT,
  created_at TEXT NOT NULL,
  CHECK (type <> 'Medical' OR document_id IS NOT NULL),
  FOREIGN KEY(community_id,student_id) REFERENCES students(community_id,id),
  FOREIGN KEY(community_id,decided_by) REFERENCES users(community_id,id)
);
CREATE INDEX leaves_dates ON leaves(community_id,start_date,end_date);
ALTER TABLE leaves ENABLE ROW LEVEL SECURITY;
ALTER TABLE leaves FORCE ROW LEVEL SECURITY;
CREATE POLICY community_isolation ON leaves
  USING (community_id=nullif(current_setting('app.community_id',true),'')::integer)
  WITH CHECK (community_id=nullif(current_setting('app.community_id',true),'')::integer);
REVOKE ALL ON leaves FROM PUBLIC;
DO $$
DECLARE r TEXT;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON leaves FROM %I',r);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hostel360_app') THEN
    GRANT SELECT,INSERT,UPDATE ON leaves TO hostel360_app;
    GRANT USAGE,SELECT ON SEQUENCE leaves_id_seq TO hostel360_app;
  END IF;
END $$;
INSERT INTO schema_migrations(version) VALUES ('20261123010000');
COMMIT;
