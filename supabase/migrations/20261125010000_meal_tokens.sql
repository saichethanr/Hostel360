-- Apply as the schema owner after the sponsor migration. Meal tokens for
-- visitors: bought online from the mess QR code (no login) or issued by staff
-- for cash or UPI. A token is Open for 2 hours after payment until staff close
-- it when the meal is served. Prices per meal are an Admin setting.
BEGIN;
SET LOCAL search_path TO hostel360;
CREATE TABLE meal_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  -- Opens the buyer's token page; the visible token number is the id.
  access_key TEXT NOT NULL UNIQUE,
  meal TEXT NOT NULL CHECK (meal IN ('Breakfast','Lunch','Dinner')),
  amount INTEGER NOT NULL CHECK (amount > 0),
  name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  mode TEXT NOT NULL CHECK (mode IN ('Online','Cash','UPI')),
  reference TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL CHECK (status IN ('Pending','Open','Closed')),
  key_id TEXT,
  provider_order_id TEXT,
  provider_payment_id TEXT UNIQUE,
  issued_by INTEGER,
  closed_by INTEGER,
  created_at TEXT NOT NULL,
  opened_at TEXT,
  expires_at TEXT,
  closed_at TEXT,
  CHECK (status = 'Pending' OR (opened_at IS NOT NULL AND expires_at IS NOT NULL)),
  UNIQUE(key_id,provider_order_id)
);
CREATE INDEX meal_tokens_created ON meal_tokens(community_id,created_at);
ALTER TABLE meal_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE meal_tokens FORCE ROW LEVEL SECURITY;
CREATE POLICY community_isolation ON meal_tokens
  USING (community_id=nullif(current_setting('app.community_id',true),'')::integer)
  WITH CHECK (community_id=nullif(current_setting('app.community_id',true),'')::integer);
REVOKE ALL ON meal_tokens FROM PUBLIC;
DO $$
DECLARE r TEXT;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON meal_tokens FROM %I',r);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hostel360_app') THEN
    GRANT SELECT,INSERT,UPDATE ON meal_tokens TO hostel360_app;
    GRANT USAGE,SELECT ON SEQUENCE meal_tokens_id_seq TO hostel360_app;
  END IF;
END $$;
INSERT INTO schema_migrations(version) VALUES ('20261125010000');
COMMIT;
