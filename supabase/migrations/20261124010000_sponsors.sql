-- Apply as the schema owner after the leave migration. Adds Sponsor accounts,
-- the sponsor wallet (contributions in, grants to students out), sponsorship
-- profiles prepared by the Admin, and online sponsor contributions.
BEGIN;
SET LOCAL search_path TO hostel360;
ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('Admin','Manager','Student','Warden','Sponsor'));
ALTER TABLE payments DROP CONSTRAINT payments_mode_check;
ALTER TABLE payments ADD CONSTRAINT payments_mode_check CHECK (mode IN ('Cash','UPI','Bank','Card','Sponsor'));

CREATE TABLE sponsors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  UNIQUE(community_id,email),
  UNIQUE(community_id,id)
);
-- Money into a sponsor's wallet: recorded by the Admin or paid online.
CREATE TABLE sponsor_contributions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  sponsor_id INTEGER NOT NULL,
  amount INTEGER NOT NULL CHECK (amount > 0),
  received_on TEXT NOT NULL,
  method TEXT NOT NULL CHECK (method IN ('Recorded','Online')),
  note TEXT NOT NULL DEFAULT '',
  provider_payment_id TEXT UNIQUE,
  recorded_by INTEGER,
  created_at TEXT NOT NULL,
  FOREIGN KEY(community_id,sponsor_id) REFERENCES sponsors(community_id,id)
);
-- Money out of a wallet to one student. Its receipts carry the idempotency key
-- sponsor-<grant id>-<category>; a reversed receipt returns money to the wallet.
CREATE TABLE sponsor_grants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  sponsor_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  amount INTEGER NOT NULL CHECK (amount > 0),
  created_by INTEGER NOT NULL,
  created_at TEXT NOT NULL,
  FOREIGN KEY(community_id,sponsor_id) REFERENCES sponsors(community_id,id),
  FOREIGN KEY(community_id,student_id) REFERENCES students(community_id,id)
);
-- A student's sponsorship profile, prepared by the Admin. share_token opens
-- the public page people share to reach more sponsors.
CREATE TABLE sponsor_listings (
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  student_id INTEGER NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  photo_document_id INTEGER REFERENCES documents(id),
  share_token TEXT NOT NULL UNIQUE,
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  listed_by INTEGER NOT NULL,
  listed_at TEXT NOT NULL,
  PRIMARY KEY(community_id,student_id),
  FOREIGN KEY(community_id,student_id) REFERENCES students(community_id,id)
);
-- Semester results and labelled supporting documents on a profile.
CREATE TABLE sponsor_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  student_id INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('Result','Document')),
  label TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  document_id INTEGER REFERENCES documents(id),
  created_at TEXT NOT NULL,
  CHECK (kind = 'Result' OR document_id IS NOT NULL),
  FOREIGN KEY(community_id,student_id) REFERENCES students(community_id,id)
);
-- Online contributions while checkout is open; paid ones become contributions.
CREATE TABLE sponsor_orders (
  id TEXT PRIMARY KEY,
  community_id INTEGER NOT NULL DEFAULT nullif(current_setting('app.community_id',true),'')::integer REFERENCES communities(id),
  user_id INTEGER NOT NULL,
  sponsor_id INTEGER NOT NULL,
  -- Set when the Sponsor chose a student; otherwise the Admin allocates.
  student_id INTEGER,
  key_id TEXT NOT NULL,
  provider_order_id TEXT,
  amount INTEGER NOT NULL CHECK (amount > 0),
  status TEXT NOT NULL CHECK (status IN ('open','paid')),
  created_at TEXT NOT NULL,
  FOREIGN KEY(community_id,sponsor_id) REFERENCES sponsors(community_id,id),
  FOREIGN KEY(community_id,student_id) REFERENCES students(community_id,id),
  UNIQUE(key_id,provider_order_id)
);
CREATE INDEX sponsor_grants_sponsor ON sponsor_grants(community_id,sponsor_id);
CREATE INDEX sponsor_files_student ON sponsor_files(community_id,student_id);
DO $$
DECLARE t TEXT; r TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['sponsors','sponsor_contributions','sponsor_grants','sponsor_listings','sponsor_files','sponsor_orders'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY',t);
    EXECUTE format('CREATE POLICY community_isolation ON %I USING (community_id=nullif(current_setting(''app.community_id'',true),'''')::integer) WITH CHECK (community_id=nullif(current_setting(''app.community_id'',true),'''')::integer)',t);
    EXECUTE format('REVOKE ALL ON %I FROM PUBLIC',t);
    FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
        EXECUTE format('REVOKE ALL ON %I FROM %I',t,r);
      END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hostel360_app') THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE ON %I TO hostel360_app',t);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='hostel360_app') THEN
    GRANT DELETE ON sponsor_files TO hostel360_app;
    GRANT USAGE,SELECT ON SEQUENCE sponsors_id_seq, sponsor_contributions_id_seq, sponsor_grants_id_seq, sponsor_files_id_seq TO hostel360_app;
  END IF;
END $$;
INSERT INTO schema_migrations(version) VALUES ('20261124010000');
COMMIT;
