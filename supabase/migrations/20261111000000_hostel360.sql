-- Initial Hostel360 schema. Application tables are private, never exposed via PostgREST.
BEGIN;
CREATE SCHEMA IF NOT EXISTS hostel360;
SET LOCAL search_path TO hostel360;
CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS students (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE, roll TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL, department TEXT NOT NULL, year INTEGER NOT NULL,
      room TEXT NOT NULL, phone TEXT NOT NULL, guardian TEXT NOT NULL DEFAULT '',
      admission_type TEXT NOT NULL DEFAULT 'Fresher', status TEXT NOT NULL DEFAULT 'Active',
      joined TEXT NOT NULL
    , course TEXT NOT NULL DEFAULT 'B.E.', academic_year TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '', guardian_phone TEXT NOT NULL DEFAULT '', exited TEXT, exit_reason TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
      password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('Admin','Manager','Student')),
      student_id INTEGER REFERENCES students(id), active INTEGER NOT NULL DEFAULT 1
    , auth_id TEXT, must_change_password INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions (
      token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires BIGINT NOT NULL
    );
CREATE TABLE IF NOT EXISTS attendance (
      student_id INTEGER NOT NULL REFERENCES students(id), date TEXT NOT NULL,
      status TEXT NOT NULL CHECK(status IN ('Present','Absent','Leave')),
      recorded_by INTEGER NOT NULL REFERENCES users(id), updated_at TEXT NOT NULL,
      PRIMARY KEY(student_id,date)
    );
CREATE TABLE IF NOT EXISTS demands (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
      category TEXT NOT NULL CHECK(category IN ('Mess','Fund','Management','Establishment')),
      period TEXT NOT NULL, description TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount > 0),
      days INTEGER, rate INTEGER, finalized_by INTEGER REFERENCES users(id),
      created_at TEXT NOT NULL, adjustment INTEGER NOT NULL DEFAULT 0, adjustment_reason TEXT NOT NULL DEFAULT '', UNIQUE(student_id,category,period,description)
    );
CREATE TABLE IF NOT EXISTS payments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
      amount INTEGER NOT NULL CHECK(amount > 0), date TEXT NOT NULL,
      mode TEXT NOT NULL CHECK(mode IN ('Cash','UPI','Bank')), reference TEXT NOT NULL,
      category TEXT NOT NULL, receipt TEXT NOT NULL UNIQUE,
      received_by INTEGER NOT NULL REFERENCES users(id), idempotency_key TEXT NOT NULL UNIQUE,
      created_at TEXT NOT NULL
    , snapshot TEXT, reversed_at TEXT, reversal_reason TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS allocations (
      payment_id INTEGER NOT NULL REFERENCES payments(id), demand_id INTEGER NOT NULL REFERENCES demands(id),
      amount INTEGER NOT NULL CHECK(amount > 0), PRIMARY KEY(payment_id,demand_id)
    );
CREATE TABLE IF NOT EXISTS receipt_sequences (category TEXT PRIMARY KEY, value INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, detail TEXT NOT NULL, created_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS applications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER REFERENCES users(id), name TEXT NOT NULL,
 roll TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL, department TEXT NOT NULL,
 course TEXT NOT NULL, year INTEGER NOT NULL, academic_year TEXT NOT NULL, guardian TEXT NOT NULL,
 address TEXT NOT NULL, admission_type TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Submitted',
 reason TEXT NOT NULL DEFAULT '', student_id INTEGER REFERENCES students(id), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS fee_components (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category TEXT NOT NULL, name TEXT NOT NULL,
 amount INTEGER NOT NULL CHECK(amount>0), academic_year TEXT NOT NULL,
 applicability TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1,
 UNIQUE(category,name,academic_year)
);
CREATE TABLE IF NOT EXISTS room_history (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
 room TEXT NOT NULL, started TEXT NOT NULL, ended TEXT, reason TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS documents (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
 name TEXT NOT NULL, path TEXT NOT NULL UNIQUE, mime TEXT NOT NULL, bytes INTEGER NOT NULL,
 uploaded_by INTEGER NOT NULL REFERENCES users(id), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS import_batches (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id INTEGER NOT NULL REFERENCES users(id), kind TEXT NOT NULL,
 rows_json TEXT NOT NULL, errors_json TEXT NOT NULL, created_at TEXT NOT NULL, committed_at TEXT
);
CREATE TABLE IF NOT EXISTS billing_periods (
 period TEXT PRIMARY KEY, snapshot TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS login_attempts (
 key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS application_roll ON applications(roll);
CREATE INDEX IF NOT EXISTS demand_student_period ON demands(student_id,period);
CREATE INDEX IF NOT EXISTS payment_student_date ON payments(student_id,date);
CREATE INDEX IF NOT EXISTS allocation_demand ON allocations(demand_id);
CREATE INDEX IF NOT EXISTS attendance_date ON attendance(date);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires);
CREATE UNIQUE INDEX IF NOT EXISTS users_auth_identity ON users(auth_id) WHERE auth_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS student_roll_casefold ON students(lower(roll));
INSERT INTO settings (key,value) VALUES ('hostel_name','Hostel360'),('daily_rate','11000'),('demo','false') ON CONFLICT DO NOTHING;
INSERT INTO schema_migrations (version) VALUES ('20261111000000') ON CONFLICT DO NOTHING;
REVOKE ALL ON SCHEMA hostel360 FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA hostel360 FROM PUBLIC;
COMMIT;
