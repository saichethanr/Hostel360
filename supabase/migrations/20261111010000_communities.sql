-- Every business table is denied by default without a transaction-local tenant.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['students','users','sessions','attendance','demands','payments',
    'allocations','receipt_sequences','settings','audit','applications','fee_components',
    'room_history','documents','import_batches','billing_periods','login_attempts'] LOOP
    EXECUTE format('ALTER TABLE %I ADD COLUMN community_id INTEGER NOT NULL DEFAULT 1 REFERENCES communities(id)',t);
    EXECUTE format('ALTER TABLE %I ALTER COLUMN community_id SET DEFAULT nullif(current_setting(''app.community_id'',true),'''')::integer',t);
    IF t IN ('students','users','demands','payments') THEN
      EXECUTE format('ALTER TABLE %I ADD UNIQUE (community_id,id)',t);
    END IF;
    EXECUTE format('CREATE INDEX ON %I (community_id)',t);
  END LOOP;
END $$;

-- Foreign keys must reject cross-community references even when an ID is known.
DO $$
DECLARE r RECORD;
BEGIN
  FOR r IN
    SELECT c.conname,child.relname AS child,parent.relname AS parent,
      (SELECT string_agg(quote_ident(a.attname),',' ORDER BY k.ord)
       FROM unnest(c.conkey) WITH ORDINALITY k(num,ord)
       JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k.num) AS child_cols,
      (SELECT string_agg(quote_ident(a.attname),',' ORDER BY k.ord)
       FROM unnest(c.confkey) WITH ORDINALITY k(num,ord)
       JOIN pg_attribute a ON a.attrelid=c.confrelid AND a.attnum=k.num) AS parent_cols
    FROM pg_constraint c JOIN pg_class child ON child.oid=c.conrelid
    JOIN pg_class parent ON parent.oid=c.confrelid
    JOIN pg_namespace n ON n.oid=child.relnamespace
    WHERE c.contype='f' AND n.nspname='hostel360'
      AND parent.relname IN ('students','users','demands','payments')
  LOOP
    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I',r.child,r.conname);
    EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (community_id,%s) REFERENCES %I (community_id,%s)',
      r.child,r.conname,r.child_cols,r.parent,r.parent_cols);
  END LOOP;
END $$;
